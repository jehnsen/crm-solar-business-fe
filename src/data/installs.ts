import type { InstallProject, MaterialItem, PunchListItem } from "@/lib/types";

function materials(
  prefix: string,
  panelCount: number,
  extras: [string, number, string, boolean][] = [],
  allStaged = true,
): MaterialItem[] {
  const base: [string, number, string, boolean][] = [
    ["Modules", panelCount, "ea", allStaged],
    ["Rail, 168in", Math.ceil(panelCount / 2), "ea", allStaged],
    ["Mid clamps", panelCount * 2, "ea", allStaged],
    ["End clamps", 8, "ea", allStaged],
    ["Flashings / mounts", Math.ceil(panelCount * 1.4), "ea", allStaged],
    ["PV wire, 10AWG", 250, "ft", allStaged],
    ["Rapid shutdown devices", panelCount, "ea", allStaged],
    ["Conduit, 3/4in EMT", 60, "ft", allStaged],
    ["AC disconnect", 1, "ea", allStaged],
    ["Placards & labels", 1, "set", allStaged],
  ];
  return [...base, ...extras].map(([name, quantity, unit, staged], i) => ({
    id: `${prefix}-mt-${i + 1}`,
    name,
    quantity,
    unit,
    staged,
  }));
}

function punch(prefix: string, items: [string, boolean, string][]): PunchListItem[] {
  return items.map(([description, resolved, raisedAt], i) => ({
    id: `${prefix}-pl-${i + 1}`,
    description,
    resolved,
    raisedAt,
  }));
}

